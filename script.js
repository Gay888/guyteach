function renderComments() {
  const list  = document.getElementById('commentsList');
  const noMsg = document.getElementById('noReviews');
  list.innerHTML = '';
  if (reviews.length === 0) { noMsg.style.display = 'block'; return; }
  noMsg.style.display = 'none';
  reviews.forEach((r, idx) => {
    const card = document.createElement('div');
    card.className = 'comment-card';
    card.innerHTML = `
      <div class="comment-header">
        <div class="comment-user">${escapeHTML(r.name)}</div>
        <div class="comment-badge">${escapeHTML(r.category)}</div>
      </div>
      <div class="comment-stars">${starsHTML(r.rating)}</div>
      <p class="comment-text">${escapeHTML(r.comment)}</p>
      <div class="comment-date">${r.date}</div>
      <div class="comment-actions">
        <button class="btn-edit" onclick="editReview(${idx})">✏️ แก้ไข</button>
        <button class="btn-delete" onclick="deleteReview(${idx})">🗑️ ลบ</button>
      </div>`;
    list.appendChild(card);
  });
}

function editReview(idx) {
  const r = reviews[idx];
  showPage('home');
  document.getElementById('reviewName').value     = r.name;
  document.getElementById('reviewCategory').value = r.category;
  document.getElementById('reviewComment').value  = r.comment;
  document.getElementById('editIndex').value      = idx;
  document.getElementById('submitBtn').textContent = 'บันทึกการแก้ไข';
  document.getElementById('cancelEditBtn').style.display = 'inline-block';
  selectedRating = r.rating;
  updateStars(selectedRating);
  document.querySelector('.review-panel').scrollIntoView({ behavior: 'smooth' });
}

function deleteReview(idx) {
  if (!confirm('ต้องการลบรีวิวนี้ใช่ไหม?')) return;
  reviews.splice(idx, 1);
  renderComments();
}

