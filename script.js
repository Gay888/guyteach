function startQuiz(courseId, chapterIdx) {
  prevPage = 'courseDetail';
  currentCourse = COURSES.find(c => c.id === courseId);
  currentChapter = chapterIdx;
  quizStartTime = Date.now();

  const ch = currentCourse.chapters[chapterIdx];
  const questions = ch.quiz;

  const content = document.getElementById('quizContent');
  content.innerHTML = `
    <div class="quiz-header">
      <h2>📝 ${ch.title}</h2>
      <p>ตอบให้ครบทุกข้อแล้วกด "ส่งคำตอบ"</p>
    </div>
    ${questions.map((q, qi) => `
      <div class="quiz-question-block">
        <div class="quiz-q">${qi + 1}. ${q.q}</div>
        <div class="quiz-options">
          ${q.opts.map((opt, oi) => `
            <label class="quiz-option" id="opt-${qi}-${oi}">
              <input type="radio" name="q${qi}" value="${oi}"> ${opt}
            </label>
          `).join('')}
        </div>
      </div>
    `).join('')}
    <button class="btn-submit-quiz" onclick="submitQuiz()">ส่งคำตอบ</button>
    <div id="quizResult"></div>`;

  showPage('quizPage');
}

function submitQuiz() {
  const ch = currentCourse.chapters[currentChapter];
  const questions = ch.quiz;
  let score = 0;
  let allAnswered = true;

  questions.forEach((q, qi) => {
    const selected = document.querySelector(`input[name="q${qi}"]:checked`);
    if (!selected) { allAnswered = false; return; }
    const chosen = parseInt(selected.value);
    if (chosen === q.ans) {
      score++;
      document.getElementById(`opt-${qi}-${chosen}`).classList.add('correct');
    } else {
      document.getElementById(`opt-${qi}-${chosen}`).classList.add('wrong');
      document.getElementById(`opt-${qi}-${q.ans}`).classList.add('correct');
    }
  });

  if (!allAnswered) {
    alert('กรุณาตอบให้ครบทุกข้อ');
    return;
  }

  // Disable inputs
  document.querySelectorAll('.btn-submit-quiz').forEach(b => b.style.display = 'none');
  document.querySelectorAll('input[type="radio"]').forEach(r => r.disabled = true);

  const elapsed = Math.round((Date.now() - quizStartTime) / 1000);
  const mins = Math.floor(elapsed / 60);
  const secs = elapsed % 60;
  const durationStr = mins > 0 ? `${mins} นาที ${secs} วินาที` : `${secs} วินาที`;

  const pct = Math.round((score / questions.length) * 100);
  let feedback = pct >= 80 ? '🎉 ยอดเยี่ยม!' : pct >= 60 ? '👍 ผ่านแล้ว ทำได้ดี' : '📖 ลองทบทวนอีกครั้งนะ';

  // Save to history
  const now = new Date();
  const dateStr = `${now.getDate()}/${now.getMonth() + 1}/${now.getFullYear() + 543}`;
  learningHistory.unshift({
    image: currentCourse.image,
    course: currentCourse.title,
    chapter: ch.title,
    date: dateStr,
    duration: durationStr,
    score: score,
    total: questions.length,
    courseId: currentCourse.id,
    chapterIdx: currentChapter,
  });

  document.getElementById('quizResult').innerHTML = `
    <div class="quiz-result">
      <div class="quiz-score">${score}/${questions.length}</div>
      <div class="quiz-score-label">คะแนนที่ได้ (${pct}%)</div>
      <div class="quiz-feedback">${feedback}</div>
      <div style="color:#666;font-size:14px;margin-bottom:20px;">⏱ ใช้เวลา ${durationStr}</div>
      <div class="quiz-result-actions">
        <button class="btn-primary" onclick="openCourse('${currentCourse.id}')">← กลับบทเรียน</button>
        <button class="btn-primary" style="background:#6c757d" onclick="showPage('history')">ดูประวัติการเรียน</button>
      </div>
    </div>`;

  document.getElementById('quizResult').scrollIntoView({ behavior: 'smooth' });
}

function exitQuiz() {
  if (prevPage === 'courseDetail') {
    openCourse(currentCourse.id);
  } else {
    showPage('home');
  }
}

