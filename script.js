function deleteHistory(idx) {
  learningHistory.splice(idx, 1);
  renderHistory();
}

function renderHistory() {
  const list = document.getElementById('historyList');
  const noMsg = document.getElementById('noHistory');
  list.innerHTML = '';
  if (learningHistory.length === 0) {
    noMsg.style.display = 'block';
    return;
  }
  noMsg.style.display = 'none';

  // Sort
  const sortSel = document.getElementById('historySortSelect');
  const sortVal = sortSel ? sortSel.value : 'default';
  let display = learningHistory.map((h, i) => ({ ...h, _origIdx: i }));
  if (sortVal === 'high') {
    display.sort((a, b) => (b.score / b.total) - (a.score / a.total));
  } else if (sortVal === 'low') {
    display.sort((a, b) => (a.score / a.total) - (b.score / b.total));
  }

  display.forEach(h => {
    const pct = Math.round((h.score / h.total) * 100);
    const origIdx = h._origIdx;
    const card = document.createElement('div');
    card.className = 'history-card';
    card.innerHTML = `
      <div class="history-card-clickable">
        <div class="history-icon">${h.image}</div>
        <div class="history-info">
          <div class="history-course">${escapeHTML(h.course)}</div>
          <div class="history-chapter">${escapeHTML(h.chapter)}</div>
          <div class="history-meta">
            <span class="history-tag date">📅 ${h.date}</span>
            <span class="history-tag duration">⏱ ${h.duration}</span>
            <span class="history-tag score">⭐ ${h.score}/${h.total} (${pct}%)</span>
          </div>
        </div>
      </div>
      <button class="btn-history-delete" title="ลบประวัตินี้">🗑</button>`;
    card.querySelector('.history-card-clickable').addEventListener('click', () => goToChapterFromHistory(h.courseId, h.chapterIdx));
    card.querySelector('.btn-history-delete').addEventListener('click', (e) => {
      e.stopPropagation();
      if (confirm('ต้องการลบประวัติการเรียนนี้ใช่ไหม?')) deleteHistory(origIdx);
    });
    list.appendChild(card);
  });
}

