// SAVED CHAPTERS (ตารางการศึกษา → คอร์สที่บันทึก)
// ============================================================
function isChapterSaved(courseId, chapterIdx) {
  return savedCourses.some(s => s.courseId === courseId && s.chapterIdx === chapterIdx);
}

function toggleSaveChapter(courseId, chapterIdx, btn) {
  const idx = savedCourses.findIndex(s => s.courseId === courseId && s.chapterIdx === chapterIdx);
  if (idx === -1) {
    const course = COURSES.find(c => c.id === courseId);
    const ch = course.chapters[chapterIdx];
    savedCourses.unshift({
      courseId,
      chapterIdx,
      courseTitle: course.title,
      chapterTitle: ch.title,
      image: course.image,
    });
    if (btn) { btn.classList.add('saved'); btn.textContent = '🔖 บันทึกแล้ว'; }
  } else {
    savedCourses.splice(idx, 1);
    if (btn) { btn.classList.remove('saved'); btn.textContent = '📌 บันทึกบทเรียน'; }
  }
  renderSavedCourses();
}

function unsaveChapter(courseId, chapterIdx) {
  savedCourses = savedCourses.filter(s => !(s.courseId === courseId && s.chapterIdx === chapterIdx));
  renderSavedCourses();
  const btn = document.getElementById(`save-btn-${courseId}-${chapterIdx}`);
  if (btn) { btn.classList.remove('saved'); btn.textContent = '📌 บันทึกบทเรียน'; }
}

function renderSavedCourses() {
  const list = document.getElementById('savedCoursesList');
  const noMsg = document.getElementById('noSaved');
  if (!list || !noMsg) return;
  list.innerHTML = '';
  if (savedCourses.length === 0) { noMsg.style.display = 'block'; return; }
  noMsg.style.display = 'none';
  savedCourses.forEach(s => {
    const card = document.createElement('div');
    card.className = 'saved-card';
    card.innerHTML = `
      <div class="saved-icon">${s.image}</div>
      <div class="saved-info">
        <div class="saved-course">${escapeHTML(s.courseTitle)}</div>
        <div class="saved-chapter">${escapeHTML(s.chapterTitle)}</div>
      </div>
      <div class="saved-actions">
        <button class="btn-edit">เปิดบทเรียน</button>
        <button class="btn-delete">ลบ</button>
      </div>`;
    card.querySelector('.btn-edit').addEventListener('click', () => goToChapterFromHistory(s.courseId, s.chapterIdx));
    card.querySelector('.btn-delete').addEventListener('click', () => unsaveChapter(s.courseId, s.chapterIdx));
    list.appendChild(card);
  });
}

// Opens a course and jumps straight to a given chapter (used by history + saved list)
function goToChapterFromHistory(courseId, chapterIdx) {
  openCourse(courseId);
  setTimeout(() => {
    document.querySelectorAll('.chapter-card').forEach(c => c.classList.remove('open'));
    const card = document.getElementById(`chapter-card-${chapterIdx}`);
    if (card) {
      card.classList.add('open');
      card.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }, 50);
}

